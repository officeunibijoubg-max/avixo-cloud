// Шаблони за главните букви. Всяко движение е в реда и посоката,
// в които детето трябва да го изпише. Първият шаблон се показва като помощ;
// останалите са допустими алтернативи при оценяването.

// Обща „коремче“ част за Б, В, Р, Ъ, Ь: от лявата черта надясно, дъга, обратно.
const bowl = (x0: number, top: number, bottom: number, reach: number) => {
  const r = (bottom - top) / 2;
  const cx = x0 + reach - r;
  return join(line([x0, top], [cx, top]), arc(cx, top + r, r, r, -90, 90), line([cx, bottom], [x0, bottom]));
};

